//! System tray (Task 19): the built-in Tauri v2 tray with the brief's
//! five-item menu — 打开主窗 / 快速搜索 / 重新全扫 / 设置 / 退出 — plus the
//! window lifecycle rules: closing the main window hides to the tray
//! (never exits; see `lib.rs`'s close handler), a tray double-click (and
//! a plain left click) shows + focuses the main window, and 退出 is the
//! REAL exit.
//!
//! Real exit vs. a running scan (the Task 8 caveat): `Engine::drop` may
//! block on a long scan's store lock, so 退出 checks `Engine::is_scanning`
//! first and, mid-scan, shows a confirm dialog — 「扫描进行中，退出将中断扫
//! 描」 — whose secondary text states why interrupting is SAFE by design:
//! the scan slot's Drop guard releases the flag on any exit path, and all
//! writes are SQLite transactions, so an interrupted scan cannot corrupt
//! the index (the next rescan heals it). The dialog is the plugin's
//! NON-blocking `show(callback)`: tray menu events fire on the main
//! thread, where `blocking_show` is documented to misbehave.
//!
//! Menu language: the labels follow `Settings.lang` (zh/en); "auto"
//! resolves from the OS UI language, mirroring the webview's
//! navigator.language rule. A later language change re-labels the menu
//! live via [`relabel`], hooked from the `settings_set` command.
//!
//! The icon is the repo's own placeholder (`icons/tray.png`, a neutral
//! folder-magnifier glyph generated by `icons/generate.ps1` — no
//! third-party logo).

use std::sync::Mutex;

use serde::Serialize;
use tauri::menu::{Menu, MenuItem};
use tauri::tray::{MouseButton, TrayIcon, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Emitter, Manager, Wry};
use tauri_plugin_dialog::{DialogExt, MessageDialogButtons, MessageDialogKind};

use crate::state::AppState;

/// The tray's own id (one tray per app).
const TRAY_ID: &str = "synso-tray";

/// Main-window label in `tauri.conf.json` (also used by the close-to-tray
/// handler and the single-instance callback).
pub const MAIN_WINDOW_LABEL: &str = "main";

/// Emitted to the main window when the tray's 设置 item picks a tab
/// (kebab-case event name, snake_case payload key — see `events.rs`
/// conventions). The dashboard's tab switcher listens for it; picking
/// the event over a URL hash keeps the mechanism identical for every
/// entry point and needs no window reload.
pub const NAV_EVENT: &str = "nav-tab";

/// [`NAV_EVENT`]'s payload: the tab id to switch to.
#[derive(Debug, Clone, Serialize)]
pub struct NavPayload {
    pub tab: String,
}

/// The two label sets, chosen by [`resolve_lang`].
struct Labels {
    open: &'static str,
    quick: &'static str,
    rescan: &'static str,
    settings: &'static str,
    quit: &'static str,
}

const ZH: Labels = Labels {
    open: "打开主窗",
    quick: "快速搜索",
    rescan: "重新全扫",
    settings: "设置",
    quit: "退出",
};

const EN: Labels = Labels {
    open: "Open Synso",
    quick: "Quick search",
    rescan: "Rescan all",
    settings: "Settings",
    quit: "Quit",
};

type Lang = &'static str;

/// `Settings.lang` → tray label set. An explicit "zh"/"en" wins; "auto"
/// (and anything else) follows the OS UI language, zh when it is Chinese,
/// English as the fallback — the same rule the webview applies to
/// `navigator.language` in `i18n/index.ts`.
fn resolve_lang(settings_lang: &str) -> Lang {
    match settings_lang {
        "zh" => "zh",
        "en" => "en",
        _ => os_primary_language().unwrap_or("en"),
    }
}

/// The OS UI language's two-letter code, when it is one we label for.
#[cfg(windows)]
fn os_primary_language() -> Option<Lang> {
    use windows::Win32::Globalization::GetUserDefaultUILanguage;
    // LANGID's low 10 bits are the primary language id (0x04 zh, 0x09 en).
    match unsafe { GetUserDefaultUILanguage() } & 0x3ff {
        0x04 => Some("zh"),
        0x09 => Some("en"),
        _ => None,
    }
}

#[cfg(not(windows))]
fn os_primary_language() -> Option<Lang> {
    None
}

fn labels(lang: Lang) -> &'static Labels {
    if lang == "zh" {
        &ZH
    } else {
        &EN
    }
}

/// Managed tray handle: the icon (for live re-labeling) plus the language
/// the current menu was built for.
pub struct TrayState {
    tray: TrayIcon<Wry>,
    lang: Mutex<Lang>,
}

/// Builds the tray: icon, five-item menu from the current settings
/// language, the menu-item handlers, and the click handlers. The tray is
/// best-effort at the app level (a failure is logged, never fatal — see
/// `lib.rs`), but a `Ok(())` return guarantees menu + handlers are live.
pub fn init(app: &AppHandle) -> Result<(), tauri::Error> {
    let settings_lang = app
        .try_state::<AppState>()
        .map(|state| state.engine.settings().lang)
        .unwrap_or_default();
    let lang = resolve_lang(&settings_lang);

    let menu = build_menu(app, lang)?;
    let tray = TrayIconBuilder::with_id(TRAY_ID)
        // The repo's own 32px placeholder (see `icons/generate.ps1`).
        // `include_image!` resolves relative to the crate manifest.
        .icon(tauri::include_image!("icons/tray.png"))
        .tooltip("Synso")
        // Menu on RIGHT click; the left button is the show-window gesture.
        .show_menu_on_left_click(false)
        .menu(&menu)
        .on_menu_event(|app, event| on_menu_item(app, event.id.as_ref()))
        .on_tray_icon_event(|tray, event| match event {
            // 双击 (and a plain left click) = show + focus the main window.
            TrayIconEvent::DoubleClick {
                button: MouseButton::Left,
                ..
            }
            | TrayIconEvent::Click {
                button: MouseButton::Left,
                ..
            } => show_main(tray.app_handle()),
            _ => {}
        })
        .build(app)?;
    app.manage(TrayState {
        tray,
        lang: Mutex::new(lang),
    });
    Ok(())
}

fn build_menu(app: &AppHandle, lang: Lang) -> Result<Menu<Wry>, tauri::Error> {
    let l = labels(lang);
    let open = MenuItem::with_id(app, "open-main", l.open, true, None::<&str>)?;
    let quick = MenuItem::with_id(app, "quick-search", l.quick, true, None::<&str>)?;
    let rescan = MenuItem::with_id(app, "rescan", l.rescan, true, None::<&str>)?;
    let settings = MenuItem::with_id(app, "settings", l.settings, true, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", l.quit, true, None::<&str>)?;
    Menu::with_items(app, &[&open, &quick, &rescan, &settings, &quit])
}

/// The five menu items, per the brief:
/// - 打开主窗: show + focus the main window;
/// - 快速搜索: the quick window, through the SAME `quick::show` path the
///   dashboard button (`quick_show`) uses;
/// - 重新全扫: `start_full_scan` + bring the main window up (the scan
///   progress lives there);
/// - 设置: main window + switch it to the settings tab (`nav-tab` event);
/// - 退出: real exit, guarded by the mid-scan confirm (see module docs).
fn on_menu_item(app: &AppHandle, id: &str) {
    match id {
        "open-main" => show_main(app),
        "quick-search" => crate::quick::show(app),
        "rescan" => {
            if let Some(state) = app.try_state::<AppState>() {
                state.engine.start_full_scan();
            }
            show_main(app);
        }
        "settings" => {
            show_main(app);
            if let Err(err) = app.emit_to(
                MAIN_WINDOW_LABEL,
                NAV_EVENT,
                NavPayload {
                    tab: "settings".to_owned(),
                },
            ) {
                log::warn!("synso: tray nav emit failed: {err}");
            }
        }
        "quit" => quit(app),
        _ => {}
    }
}

/// Shows + focuses the main window (un-minimize first, so a minimized
/// window comes back). Shared by the tray's 打开主窗 / double-click, the
/// single-instance callback and the 重新全扫 / 设置 items.
pub fn show_main(app: &AppHandle) {
    if let Some(win) = app.get_webview_window(MAIN_WINDOW_LABEL) {
        let _ = win.unminimize();
        let _ = win.show();
        let _ = win.set_focus();
    }
}

/// The real exit. Mid-scan, a warning dialog stands in front of it (see
/// the module docs for the safety wording); the dialog's callback — NOT
/// the main thread — performs the `app.exit`, because tray events run on
/// the main thread and the dialog must not block it.
pub fn quit(app: &AppHandle) {
    let scanning = app
        .try_state::<AppState>()
        .is_some_and(|state| state.engine.is_scanning());
    if !scanning {
        app.exit(0);
        return;
    }
    let lang = app
        .try_state::<TrayState>()
        .and_then(|state| state.lang.lock().ok().map(|guard| *guard))
        .unwrap_or("en");
    let l = labels(lang);
    let (title, body) = if lang == "zh" {
        (
            "扫描进行中",
            "扫描进行中，退出将中断扫描。\n\n中断是安全的：扫描槽位的守卫会在退出时释放，所有写入都通过 SQLite 事务提交，索引不会损坏——下次扫描会自动补齐。",
        )
    } else {
        (
            "Scan in progress",
            "A scan is running — quitting will interrupt it.\n\nInterrupting is safe by design: the scan slot's guard releases on exit and every write commits through an SQLite transaction, so the index cannot be corrupted — the next scan heals it.",
        )
    };
    let handle = app.clone();
    app.dialog()
        .message(body)
        .title(title)
        .kind(MessageDialogKind::Warning)
        .buttons(MessageDialogButtons::OkCancelCustom(
            l.quit.to_owned(),
            if lang == "zh" { "取消" } else { "Cancel" }.to_owned(),
        ))
        .show(move |confirmed| {
            if confirmed {
                handle.exit(0);
            }
        });
}

/// Rebuilds the menu for `settings_lang` when the resolved language
/// changed (called from `settings_set`, so the tray follows the language
/// switch live). Menu ids never change, so the `on_menu_event` handler
/// keeps working across rebuilds.
pub fn relabel(app: &AppHandle, settings_lang: &str) {
    let Some(state) = app.try_state::<TrayState>() else {
        return;
    };
    let lang = resolve_lang(settings_lang);
    let mut current = state
        .lang
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    if *current == lang {
        return;
    }
    match build_menu(app, lang) {
        Ok(menu) => {
            if let Err(err) = state.tray.set_menu(Some(menu)) {
                log::warn!("synso: tray relabel to {lang:?} failed: {err}");
                return;
            }
            *current = lang;
            log::info!("synso: tray relabeled to {lang:?}");
        }
        Err(err) => log::warn!("synso: tray relabel menu build failed: {err}"),
    }
}
